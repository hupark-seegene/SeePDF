#!/usr/bin/env node
/**
 * Performance baseline harness — SKELETON (WORKPLAN 0.11, ARCHITECTURE §13/§14).
 *
 * Stage 0 records what exists without a backend: the frontend bundle numbers and the run's
 * environment. Every engine row (open, tile, text layer, search, save, OCR) is filled in by Stage 2,
 * which drives the release binary over `fixtures/` plus a generated 500-page document; the CI gate is
 * ±20 % against the recorded numbers.
 *
 * Usage:
 *   node scripts/perf-baseline.mjs            # print the table
 *   node scripts/perf-baseline.mjs --write    # write docs/perf/baseline.md
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { arch, cpus, platform, totalmem } from "node:os";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "docs", "perf", "baseline.md");
const write = process.argv.includes("--write");

/** Every budget of ARCHITECTURE §13. `value` stays null until a harness measures it. */
const ROWS = [
  { id: "launch.welcome", scenario: "Cold launch → welcome visible", target: "≤ 700 ms", owner: "Stage 2", value: null },
  { id: "open.tracemonkey", scenario: "Open 14-page PDF → first page painted", target: "≤ 250 ms", owner: "Stage 2", value: null },
  { id: "open.500p", scenario: "Open 500-page PDF → first page painted", target: "≤ 400 ms", owner: "Stage 2", value: null },
  { id: "thumbs.500p", scenario: "Thumbnail rail, 500 pages (visible)", target: "≤ 500 ms", owner: "Stage 2", value: null },
  { id: "scroll.fps", scenario: "Scroll at 100 %, continuous", target: "60 fps", owner: "(c)", value: null },
  { id: "zoom.step", scenario: "Zoom step → sharp", target: "≤ 16 ms / ≤ 250 ms", owner: "(c)", value: null },
  { id: "render.a4", scenario: "Page render A4 @150 DPI (p50/p95)", target: "≤ 30 / 120 ms", owner: "Stage 2", value: null },
  { id: "search.500p", scenario: "Search 500 pages (first hit / full)", target: "≤ 150 ms / 2.5 s", owner: "Stage 2", value: null },
  { id: "annot.create", scenario: "Annotation create → visible", target: "≤ 16 ms", owner: "(d)", value: null },
  { id: "undo", scenario: "Undo (≤ 5 MB document)", target: "≤ 50 ms", owner: "Stage 2", value: null },
  { id: "save.10mb", scenario: "Save, 10 MB document", target: "≤ 300 ms", owner: "Stage 2", value: null },
  { id: "export.14p", scenario: "Export 14 pages @150 DPI PNG", target: "≤ 400 ms", owner: "Stage 2", value: null },
  { id: "ocr.page", scenario: "OCR 1 page A4 @300 DPI ko+en", target: "≤ 2 s", owner: "(f)", value: null },
  { id: "rss.500p", scenario: "Idle RSS, 500-page document", target: "≤ 400 MB", owner: "Stage 2", value: null },
];

function frontendRows() {
  if (!existsSync(join(ROOT, "dist"))) return [];
  const json = execFileSync(process.execPath, [join(ROOT, "scripts", "check-bundle-size.mjs"), "--json"], {
    encoding: "utf8",
  });
  const report = JSON.parse(json);
  return [
    { id: "bundle.criticalGz", scenario: "Frontend critical path (entry JS + CSS, gz)", target: "≤ 120 kB", owner: "Stage 0", value: `${report.criticalGzKb} kB` },
    { id: "bundle.dist", scenario: "Frontend dist total", target: "≤ 2048 kB", owner: "Stage 0", value: `${report.totalKb} kB` },
  ];
}

const rows = [...frontendRows(), ...ROWS];
const host = `${platform()}/${arch()} · ${cpus()[0]?.model ?? "cpu"} · ${Math.round(totalmem() / 1024 ** 3)} GB`;
const version = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).version;

const table = [
  "| id | Scenario | Target | Measured | Owner |",
  "|---|---|---|---|---|",
  ...rows.map((r) => `| \`${r.id}\` | ${r.scenario} | ${r.target} | ${r.value ?? "— *(not measured yet)*"} | ${r.owner} |`),
].join("\n");

const doc = `# SeePDF — performance baseline

Generated by \`scripts/perf-baseline.mjs\`. Targets come from \`ARCHITECTURE.md\` §13; CI compares
against the **Measured** column with a ±20 % tolerance once Stage 2 turns the gate on.

* Recorded: ${new Date().toISOString()}
* Version: ${version}
* Host: ${host}

${table}

## How to fill this in

1. \`npm run build && node scripts/check-bundle-size.mjs --json\` — the two frontend rows (automatic).
2. \`npm run tauri build -- --debug\` then \`SeePDF.app/Contents/MacOS/seepdf --smoke fixtures/tracemonkey.pdf\`
   for open/render/text rows; the harness in Stage 2 drives \`fixtures/\` plus \`fixtures/gen/500p.pdf\`.
3. Re-run with \`--write\`; commit the diff in the same PR as the change that moved a number.
`;

if (write) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, doc);
  console.log(`[perf] wrote ${OUT.slice(ROOT.length + 1)}`);
} else {
  console.log(doc);
}
